// Builds docs/data.js (the data behind the demo site) from the saved live runs in data/runs/.
// No model output is edited: records are only trimmed (the raw text is dropped to keep the file small).
//   node src/site/build-data.ts

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = "data/runs";
const files = readdirSync(dir).filter((f) => f.endsWith(".json")).sort();

const runs = files.map((file) => {
  const d = JSON.parse(readFileSync(`${dir}/${file}`, "utf8"));
  const records = (d.records as any[]).map((r) => ({
    scenarioId: r.scenarioId,
    run: r.run,
    status: r.status,
    reason: r.reason ?? null,
    error: r.error ? String(r.error).slice(0, 160) : null,
    order: r.order ?? null,
    breaches: r.breaches ?? [],
    gates: r.gates
      ? Object.fromEntries(Object.entries(r.gates).map(([k, v]: [string, any]) => [k, { decision: v.decision, reasons: v.reasons }]))
      : null,
    paypal: r.paypal
      ? { id: r.paypal.id ?? null, status: r.paypal.status ?? null, matches: r.paypal.matches ?? null, error: r.paypal.error ?? null }
      : null,
  }));
  return { file, meta: d.meta, records };
});

mkdirSync("docs", { recursive: true });
const out = { generatedAt: new Date().toISOString(), runs };
writeFileSync("docs/data.js", `// Generated by src/site/build-data.ts from data/runs/. Do not edit by hand.\nexport const data = ${JSON.stringify(out)};\n`);
console.log(`docs/data.js: ${runs.length} runs, ${runs.reduce((n, r) => n + r.records.length, 0)} records`);
