// Bundles the live endpoint (src/worker + the code it uses) into ONE file, worker/worker.js,
// that can be pasted into the Cloudflare Workers dashboard editor.
//   node scripts/build-worker.mjs          (TSC=/path/to/tsc to override "npx tsc")

import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync, mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const out = mkdtempSync(join(tmpdir(), "crashcart-worker-"));
const tsc = process.env.TSC ? [process.env.TSC] : ["npx", "tsc"];
execFileSync(
  tsc[0],
  [...tsc.slice(1), "--ignoreConfig", "--outDir", out, "--rootDir", "src", "--module", "ESNext", "--target", "ES2022", "--moduleResolution", "Bundler", "--rewriteRelativeImportExtensions", "--skipLibCheck", "--strict", "--lib", "ES2022,DOM", "src/worker/index.ts"],
  { stdio: "inherit" }
);

// Dependency order: each file only uses files listed before it.
const order = ["scenarios/index.js", "scenarios/level2.js", "core/judge.js", "core/gate.js", "core/paypal.js", "agent/shopper.js", "agent/llm.js", "paypal/sandbox.js", "worker/index.js"];
const chunks = order.map((file) => {
  const names = [];
  const body = readFileSync(join(out, file), "utf8")
    .replace(/^import [\s\S]*?;\s*$/gm, "")
    .replace(/^export \{\};?\s*$/gm, "")
    .replace(/^export (const|let|function|class|async function) (\w+)/gm, (_m, kw, n) => {
      names.push(n);
      return `${kw} ${n}`;
    });
  return `// --- ${file} ---\nconst { ${names.join(", ")} } = (() => {\n${body}\nreturn { ${names.join(", ")} };\n})();`;
});
mkdirSync("worker", { recursive: true });
writeFileSync("worker/worker.js", `// GENERATED by scripts/build-worker.mjs from src/. Do not edit by hand.\n// Cloudflare Worker: live attack endpoint for the Crashcart demo site.\n${chunks.join("\n\n")}\n\nexport default worker;\n`);
rmSync(out, { recursive: true, force: true });
console.log("worker/worker.js written");
